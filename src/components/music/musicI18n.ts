export function normalizeMusicLang(appLang?: AppLanguage | string): MusicLang {
  if (appLang === 'en' || appLang === 'fr' || appLang === 'zh' || appLang === 'ca' || appLang === 'es') {
    return appLang;
  }
  if (appLang === 'rif') return 'fr';
  return 'es';
}

